#: Незаполненные реквизиты в config.py выглядят так. Установщик с ними
#: собирать можно (стенд, внутренние прогоны), но перед отправкой заказчику
#: их нужно заполнить — об этом предупреждаем громко.
PLACEHOLDER = "___________________"


def _requisites() -> str:
    """Блок реквизитов; незаполненные поля пропускаются.

    Строка `___________________` в подписанном заказчиком документе выглядит
    как недоделка, а банковские реквизиты соглашению об использовании и не
    нужны — это не платёжный документ. Лучше короткий блок из заполненного,
    чем полный из прочерков.
    """
    rows = [
        ("Наименование", EXECUTOR["name"]),
        ("ИИН", EXECUTOR["iin"]),
        ("Вид деятельности", EXECUTOR["oked"]),
        ("Адрес", EXECUTOR["address"]),
        ("Телефон", EXECUTOR["phone"]),
        ("Электронная почта", EXECUTOR["email"]),
        ("Банк", EXECUTOR["bank"]),
        ("ИИК", EXECUTOR["iik"]),
    ]
    rows = [(name, value) for name, value in rows if value and value != PLACEHOLDER]
    width = max(len(name) for name, _ in rows)
    return "\n".join(f"    {name.ljust(width)}   {value}" for name, value in rows)


