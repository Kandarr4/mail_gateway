def version_defines() -> str:
    """`#define` для mail_gateway.iss — чтобы версия правилась в одном месте."""
    return f"""\
; Создаётся installer/make_license.py — не править руками.
; Источники: app/__init__.py (версия) и docs/generate/config.py (реквизиты).
#define AppVersion "{__version__}"
#define AppName "{PRODUCT['name']}"
#define AppPublisher "{EXECUTOR['name']}"
#define AppPublisherEmail "{EXECUTOR['email']}"
#define AppLicensingURL "https://somnium.kz/licensing"
"""


def main() -> int:
    # BOM обязателен: Inno Setup 6 читает LicenseFile без него как ANSI, и
    # русский текст соглашения превращается в мусор на первом же экране.
    LICENSE_FILE.write_text(license_text(), encoding="utf-8-sig")
    VERSION_FILE.write_text(version_defines(), encoding="utf-8-sig")
    print(f"Соглашение:      {LICENSE_FILE}")
    print(f"Переменные ISS:  {VERSION_FILE}")

    missing = sorted(key for key, value in EXECUTOR.items() if value == PLACEHOLDER)
    if missing:
        print(
            "\nНезаполненные реквизиты (в соглашение не попали): "
            + ", ".join(missing)
            + ".\nЗаполнить: docs/generate/config.py, словарь EXECUTOR."
        )
    return 0


