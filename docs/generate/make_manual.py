        "cursor = 0  # сохраните это число у себя между запусками\n\n"
        "while True:\n"
        "    answer = requests.get(\n"
        '        "http://localhost:8025/api/v1/messages",\n'
        '        headers={"Authorization": "Bearer ВАШ_ТОКЕН"},\n'
        '        params={"direction": "incoming", "since_id": cursor},\n'
        "    ).json()\n\n"
        '    for letter in answer["items"]:\n'
