def build():
    from styling import new_document

    doc = new_document()
    footer_note(doc, f"{PRODUCT['name']} {PRODUCT['version']} — инструкция по запуску и настройке")

    _cover(doc)
    _what_is_it(doc)
    _before_you_start(doc)
    page_break(doc)
    _first_run(doc)
    _env(doc)
    page_break(doc)
    _dns(doc)
    page_break(doc)
    _whitelist(doc)
    page_break(doc)
    _panel(doc)
    _sending(doc)
    page_break(doc)
    _receiving(doc)
    _backup(doc)
    page_break(doc)
    _troubleshooting(doc)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    return OUTPUT


