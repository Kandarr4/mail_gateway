    heading(doc, "Шаг 1. Обратная запись PTR", 2)
    para(
        doc,
        "Самое частое препятствие. PTR — это «обратный адрес»: почтовая система "
        "получателя проверяет, что ваш IP честно называет себя вашим именем. "
        "Настроить её у регистратора домена нельзя — только у того, кто выдал "
        "вам IP-адрес.",
    )
    para(doc, "Напишите в поддержку хостера или провайдера примерно так:")
    code(
        doc,
        "Здравствуйте!\n\n"
        f"Прошу настроить обратную запись PTR для IP-адреса {IP}\n"
        f"на имя {HOST}\n\n"
        "Адрес используется как почтовый сервер нашей организации.\n"
        "Прямая запись A уже настроена и указывает на этот же адрес.",
    )
    para(doc, "Проверить результат:")
    code(doc, f"nslookup {IP}")
    para(doc, f"В ответе должно быть {HOST}, а не что-то вроде "
              "client.fttb.provider.kz.")

    heading(doc, "Шаг 2. Проверка по чёрным спискам", 2)
    para(
        doc,
        "IP-адрес мог попасть в чёрные списки ещё до вас — например, если "
        "прежний владелец рассылал спам. Проверьте бесплатно:",
    )
    bullets(
        doc,
        [
            "mxtoolbox.com/blacklists.aspx — проверяет сразу по сотне списков",
            "multirbl.valli.org — то же самое, более подробно",
        ],
    )
    para(
        doc,
        "Если адрес где-то числится, на сайте каждого списка есть форма "
        "исключения («delisting», «removal»). Обычно достаточно указать адрес и "
        "подтвердить, что рассылок не ведёте. Срок — от часа до нескольких дней.",
    )

    heading(doc, "Шаг 3. Постепенный выход на объём", 2)
    para(
        doc,
        "Новый почтовый сервер, внезапно отправивший тысячу писем, выглядит для "
        "принимающей стороны как взломанный. Первую неделю держитесь в пределах "
        "нескольких десятков писем в день, дальше увеличивайте плавно.",
    )

    heading(doc, "Если провайдер не открывает порт 25", 2)
    para(
        doc,
        "Такое бывает, и это не тупик. Отправку можно вести через почтового "
        "провайдера, а приём оставить своим. В .env указывается:",
    )
    code(
        doc,
        "MG_OUTBOUND_MODE=relay\n"
        "MG_RELAY_HOST=smtp.ps.kz\n"
        "MG_RELAY_PORT=587\n"
        "MG_RELAY_USERNAME=ваш логин\n"
        "MG_RELAY_PASSWORD=ваш пароль",
    )
    para(
        doc,
        "В этом режиме о репутации, PTR и подписи заботится провайдер — шагов "
        "выше не потребуется вовсе.",
    )


