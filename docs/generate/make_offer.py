import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from config import EXECUTOR, PRICES, PRODUCT, TERMS, money
from styling import (
    bullets,
    footer_note,
    heading,
    note,
    page_break,
    para,
    rich,
    table,
    title,
)

OUTPUT = Path(__file__).resolve().parent.parent / "ТЗ и коммерческое предложение.docx"

TOTAL_FIRST_YEAR = PRICES["license_year"] + PRICES["setup_package"]


def build():
    from styling import new_document

    doc = new_document()
    footer_note(doc, f"{EXECUTOR['name']} — {PRODUCT['name']} {PRODUCT['version']}")

    _cover(doc)
    page_break(doc)
    _purpose(doc)
    _features(doc)
    page_break(doc)
    _delivery(doc)
    _requirements(doc)
    _limits(doc)
    page_break(doc)
    _pricing(doc)
    _license(doc)
    page_break(doc)
    _terms(doc)
    _why(doc)
    _requisites(doc)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    return OUTPUT


